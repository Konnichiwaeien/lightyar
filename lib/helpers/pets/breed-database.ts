/**
 * Searches for a breed entry in the database by performing robust normalizations
 * @param breedName The raw breed name from Strapi/pet data
 * @returns Matched BreedInfo object, or the default "метис" entry
 */
export function getBreedInfo(breedName: string): BreedInfo {
  if (!breedName) return breedDatabase["метис"];
  
  const clean = breedName.toLowerCase().replace(/[-–—_]/g, " ").trim();
  
  // Direct match
  if (breedDatabase[clean]) {
    return breedDatabase[clean];
  }
  
  // Substring match: check if database key is contained in clean name or vice-versa
  for (const key of Object.keys(breedDatabase)) {
    if (key !== "метис" && (clean.includes(key) || key.includes(clean))) {
      return breedDatabase[key];
    }
  }
  
  // Fallback to "метис" but return the original name in the object
  return {
    ...breedDatabase["метис"],
    name: breedName // keep the actual name e.g. "Метис спаниеля" or custom breed
  };
}
