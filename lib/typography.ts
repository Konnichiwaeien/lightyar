/**
 * Русская типографика для текстов страницы «О нас».
 *
 * Пропускаем через неё и материал из CMS, и запасной: редактор не обязан
 * расставлять неразрывные пробелы руками, а предлог, повисший в конце строки,
 * читается как опечатка.
 *
 * Функция чистая и работает одинаково на сервере и в браузере, поэтому
 * гидратация не расходится.
 */

const NBSP = " ";

/** Однобуквенные слова не отрываются от следующего за ними. */
const SHORT_WORD = /(?<=^|[\s(«„])([аиоуявкс])[ \t]+/gi;

/** Дефис между пробелами — это набранное на скорую руку тире. */
const HYPHEN_AS_DASH = /(?<=[^\s-])[ \t]+-[ \t]+(?=\S)/g;

/** Тире не отрывается от предыдущего слова, но переносится вместе со следующим. */
const DASH = /[ \t]+—/g;

/** Сокращения вроде «т. д.» не должны разрываться переносом. */
const ABBREVIATION = /\bт\.[ \t]*([дпе])\./g;

export function applyRussianTypography(value: string): string {
  return value
    .replace(HYPHEN_AS_DASH, `${NBSP}— `)
    .replace(SHORT_WORD, `$1${NBSP}`)
    .replace(DASH, `${NBSP}—`)
    .replace(ABBREVIATION, `т.${NBSP}$1.`)
    .replace(/[ \t]{2,}/g, " ");
}
