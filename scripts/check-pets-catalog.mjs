import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.argv[2] || 'http://localhost:3000';
const out = '../tmp/pets-qa';
await fs.mkdir(out,{recursive:true});
const browser = await chromium.launch({channel:'chrome',headless:true});
const report = {viewports:[],interactions:[],errors:[],resources:{}};
let axe;
try { axe = await fs.readFile('../tmp/axe.min.js','utf8'); } catch {}
try { if(!axe) axe = await fetch('https://cdnjs.cloudflare.com/ajax/libs/axe-core/4.10.3/axe.min.js').then(r=>{if(!r.ok)throw Error(r.status);return r.text();}); } catch(e){report.axeUnavailable=String(e);}
for(const width of (process.argv.includes('--flows-only') ? [] : [320,390,768,1024,1440,1920])) {
  const context=await browser.newContext({viewport:{width,height:900}});
  const page=await context.newPage();
  page.on('pageerror',error=>report.errors.push({width,message:error.message}));
  await page.goto(base+'/pets',{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  for(const card of await page.locator('.pet-entry').all()){await card.scrollIntoViewIfNeeded();}
  await page.locator('.pets-meeting').scrollIntoViewIfNeeded();
  await page.evaluate(async()=>{await Promise.all([...document.images].filter(i=>i.loading!=='lazy'||i.getBoundingClientRect().top<innerHeight).map(i=>i.decode().catch(()=>{})));});
  await page.waitForFunction(()=>document.querySelectorAll('.pet-entry__image').length===12 && [...document.querySelectorAll('.pet-entry__image')].every(image=>image.complete && image.naturalWidth>0));
  const geometry=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,offenders:[...document.querySelectorAll('main *')].filter(e=>{const r=e.getBoundingClientRect();return r.width>0&&(r.left< -1||r.right>innerWidth+1)}).slice(0,8).map(e=>({tag:e.tagName,class:e.className,width:e.getBoundingClientRect().width})),cards:document.querySelectorAll('.pet-entry').length,heading:document.querySelectorAll('h1').length}));
  assert.ok(geometry.scroll <= width,JSON.stringify(geometry));
  assert.equal(geometry.heading,1);
  assert.equal(geometry.cards,12);
  if(axe && [320,1440].includes(width)){
    await page.addScriptTag({content:axe});
    geometry.axe=await page.evaluate(async()=>{const r=await window.axe.run(document.querySelector('main'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));});
  }
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  if([320,390,1440].includes(width)){
    await page.screenshot({path:out+'/hero-'+width+'.png'});
    await page.locator('#pets-catalog').evaluate(e=>window.scrollTo({top:e.getBoundingClientRect().top+scrollY+36,behavior:'instant'}));
    await page.screenshot({path:out+'/catalog-'+width+'.png'});
    await page.addStyleTag({content:'.pet-entry{content-visibility:visible!important}'});
    await page.screenshot({path:out+'/full-'+width+'.png',fullPage:true});
  }
  report.viewports.push(geometry);
  await fs.writeFile(out+'/report.json',JSON.stringify(report,null,2));
  await context.close();
}
